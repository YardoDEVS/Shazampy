def download(url, path):
    info("Downloading " + url)
    request = urllib.request.Request(
        url,
        headers={"User-Agent": "Shazampy installer/1.1"},
    )
    with urllib.request.urlopen(request, timeout=90) as response:
        with path.open("wb") as fh:
            shutil.copyfileobj(response, fh)


def install_windows_fonts(dest_dir, dry_run):
    """Install a broad Noto set privately beside Shazampy.

    The application registers these fonts only for its own process, so this
    does not require administrator rights or change Windows' global Fonts
    folder. The download is large because broad world-script coverage is not
    small.
    """
    font_dir = dest_dir / "fonts"
    if dry_run:
        info("Would download broad Noto world-script fonts into " + str(font_dir))
        return

    font_dir.mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory(prefix="shazampy-fonts-") as tmp:
        tmp = Path(tmp)

        # Non-CJK Noto collection: extract regular TTF faces only.
        non_cjk_zip = tmp / "noto-fonts.zip"
        try:
            download(NOTO_NON_CJK_ZIP, non_cjk_zip)
            with zipfile.ZipFile(str(non_cjk_zip), "r") as archive:
                for member in archive.namelist():
                    lower = member.lower()
                    name = Path(member).name
                    if (
                        "/hinted/ttf/" in lower
                        and lower.endswith("-regular.ttf")
                        and name
                    ):
                        target = font_dir / name
                        if not target.exists():
                            target.write_bytes(archive.read(member))
        except Exception as exc:
            warn("Could not download/extract the non-CJK Noto collection: " + str(exc))

        # CJK super collection: Japanese, Korean and Chinese coverage.
        cjk_zip = tmp / "noto-cjk.zip"
        try:
            download(NOTO_CJK_ZIP, cjk_zip)
            with zipfile.ZipFile(str(cjk_zip), "r") as archive:
                for member in archive.namelist():
                    lower = member.lower()
                    if lower.endswith((".ttc", ".ttf", ".otf")):
                        name = Path(member).name
                        if name:
                            (font_dir / name).write_bytes(archive.read(member))
        except Exception as exc:
            warn("Could not download/extract Noto CJK: " + str(exc))

    count = sum(1 for p in font_dir.iterdir() if p.suffix.lower() in (".ttf", ".otf", ".ttc"))
    if count:
        ok("Installed " + str(count) + " private Noto font files for multilingual lyrics.")
    else:
        warn("No bundled Noto fonts were installed. Windows system-font fallback will be used.")


def write_linux_app(dest_dir, force, dry_run):
    target = dest_dir / LINUX_FILENAME
    if target.exists() and not force:
        fail(str(target) + " already exists. Re-run with --force to overwrite it.")
    info("Installing Linux Shazampy to " + str(target))
    if not dry_run:
        target.write_bytes(decode_payload(LINUX_PAYLOAD_B64))
        target.chmod(0o755)
        launcher = dest_dir / "shazampy"
        try:
            if launcher.exists() or launcher.is_symlink():
                if force:
                    launcher.unlink()
                else:
                    return target
            launcher.symlink_to(LINUX_FILENAME)
        except OSError as exc:
            warn("Could not create convenience symlink: " + str(exc))
    return target


def write_windows_app(dest_dir, force, dry_run):
    target = dest_dir / WINDOWS_FILENAME
    if target.exists() and not force:
        fail(str(target) + " already exists. Re-run with --force to overwrite it.")
    info("Installing Windows Shazampy to " + str(target))
    if not dry_run:
        target.write_bytes(decode_payload(WINDOWS_PAYLOAD_B64))
        bat = dest_dir / "run_shazampy.bat"
        python_exe = sys.executable
        bat.write_text(
            '@echo off\r\n"' + python_exe + '" "' + str(target) + '"\r\n',
            encoding="utf-8",
        )
        ok("Created Windows launcher: " + str(bat))
    return target


def verify_linux():
    missing = []
    for cmd in ("ffmpeg", "songrec", "pactl"):
        if not shutil.which(cmd):
            missing.append(cmd)
    try:
        import tkinter  # noqa
    except Exception:
        missing.append("Python Tkinter module")
    try:
        import requests  # noqa
    except Exception:
        missing.append("Python requests module")
    return missing


def verify_windows():
    missing = []
    try:
        import tkinter  # noqa
    except Exception:
        missing.append("Python Tkinter module")
    try:
        import requests  # noqa
    except Exception:
        missing.append("requests")
