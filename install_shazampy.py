def install_linux_dependencies(dry_run):
    osr = read_os_release()
    os_id = osr.get("ID", "").lower()
    like = osr.get("ID_LIKE", "").lower().split()

    if os_id in ("arch", "manjaro", "endeavouros") or "arch" in like:
        install_arch(dry_run)
        return "Arch Linux family"
    if os_id == "ubuntu":
        install_ubuntu_or_debian("ubuntu", dry_run)
        return "Ubuntu"
    if os_id == "debian" or "debian" in like:
        install_ubuntu_or_debian("debian", dry_run)
        return "Debian family"
    if os_id == "fedora" or "fedora" in like or "rhel" in like:
        install_fedora(dry_run)
        return "Fedora family"

    fail(
        "Automatic Linux package installation currently supports Arch-family, "
        "Ubuntu/Debian-family and Fedora-family systems. Use --skip-packages "
        "after installing Python/Tkinter, requests, ffmpeg, SongRec, pactl and "
        "a PulseAudio-compatible audio server manually."
    )


def windows_version_info():
    release = platform.release()
    version = platform.version()
    return release, version


def check_windows_python():
    if platform.architecture()[0] != "64bit":
        fail("Shazampy_Win.py currently targets Windows x64 only.")

    major, minor = sys.version_info[:2]
    release, version = windows_version_info()

    # Windows 7 cannot run CPython 3.9+ officially. Python 3.8.10 is the last
    # CPython release with an official Windows 7 installer.
    is_win7 = release == "7" or version.startswith("6.1")

    if is_win7:
        if (major, minor) != (3, 8):
            fail(
                "Windows 7 x64 requires Python 3.8.x for this compatibility "
                "profile. Install Python 3.8.10 x64, then run this installer again."
            )
    else:
        if (major, minor) < (3, 8) or (major, minor) > (3, 12):
            fail(
                "Windows 10/11 x64: use Python 3.8 through 3.12 for this release."
            )

    return is_win7


def pip_install_windows(dry_run):
    packages = [
        "requests==2.32.3",
        "PyAudioWPatch==0.2.12.8",
        "shazamio==0.6.0",
        "shazamio-core==1.0.7",
    ]
    cmd = [sys.executable, "-m", "pip", "install", "--upgrade"] + packages
    run(cmd, dry_run=dry_run)


def download(url, path):
    info("Downloading " + url)
    request = urllib.request.Request(
        url,
        headers={"User-Agent": "Shazampy installer/1.1"},
    )
    with urllib.request.urlopen(request, timeout=90) as response:
        with path.open("wb") as fh:
            shutil.copyfileobj(response, fh)


def install_windows_fonts(dest_dir, dry_run):
    """Install a broad Noto set privately beside Shazampy.

    The application registers these fonts only for its own process, so this
    does not require administrator rights or change Windows' global Fonts
    folder. The download is large because broad world-script coverage is not
    small.
    """
    font_dir = dest_dir / "fonts"
    if dry_run:
        info("Would download broad Noto world-script fonts into " + str(font_dir))
        return

    font_dir.mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory(prefix="shazampy-fonts-") as tmp:
        tmp = Path(tmp)

        # Non-CJK Noto collection: extract regular TTF faces only.
        non_cjk_zip = tmp / "noto-fonts.zip"
        try:
            download(NOTO_NON_CJK_ZIP, non_cjk_zip)
            with zipfile.ZipFile(str(non_cjk_zip), "r") as archive:
                for member in archive.namelist():
                    lower = member.lower()
                    name = Path(member).name
                    if (
                        "/hinted/ttf/" in lower
                        and lower.endswith("-regular.ttf")
                        and name
                    ):
                        target = font_dir / name
                        if not target.exists():
                            target.write_bytes(archive.read(member))
        except Exception as exc:
            warn("Could not download/extract the non-CJK Noto collection: " + str(exc))

        # CJK super collection: Japanese, Korean and Chinese coverage.
        cjk_zip = tmp / "noto-cjk.zip"
        try:
            download(NOTO_CJK_ZIP, cjk_zip)
            with zipfile.ZipFile(str(cjk_zip), "r") as archive:
                for member in archive.namelist():
                    lower = member.lower()
                    if lower.endswith((".ttc", ".ttf", ".otf")):
                        name = Path(member).name
                        if name:
                            (font_dir / name).write_bytes(archive.read(member))
        except Exception as exc:
            warn("Could not download/extract Noto CJK: " + str(exc))

    count = sum(1 for p in font_dir.iterdir() if p.suffix.lower() in (".ttf", ".otf", ".ttc"))
    if count:
        ok("Installed " + str(count) + " private Noto font files for multilingual lyrics.")
    else:
        warn("No bundled Noto fonts were installed. Windows system-font fallback will be used.")


def write_linux_app(dest_dir, force, dry_run):
    target = dest_dir / LINUX_FILENAME
    payload = decode_payload(LINUX_PAYLOAD_B64)

    if target.exists():
        try:
            existing = target.read_bytes()
        except OSError:
            existing = None

        if existing == payload:
            info("Shazampy source is already present in the destination; keeping it.")
        elif force:
            info("Replacing existing Linux Shazampy because --force was requested.")
            if not dry_run:
                target.write_bytes(payload)
        else:
            warn(
                str(target)
                + " already exists and differs from the embedded copy; "
                + "leaving it untouched. Use --force only if you want to replace it."
            )
    else:
        info("Installing Linux Shazampy to " + str(target))
        if not dry_run:
            target.write_bytes(payload)

    if not dry_run:
        try:
            target.chmod(0o755)
        except OSError as exc:
            warn("Could not mark shazampy.py as executable: " + str(exc))

        launcher = dest_dir / "shazampy"
        try:
            if launcher.is_symlink():
                if launcher.resolve(strict=False) != target.resolve(strict=False):
                    launcher.unlink()
                    launcher.symlink_to(LINUX_FILENAME)
            elif launcher.exists():
                warn(
                    "A file named 'shazampy' already exists; "
                    "the convenience symlink was not changed."
                )
            else:
                launcher.symlink_to(LINUX_FILENAME)
                ok("Created launcher: " + str(launcher))
        except OSError as exc:
            warn("Could not create convenience symlink: " + str(exc))

    return target


def write_windows_app(dest_dir, force, dry_run):
    target = dest_dir / WINDOWS_FILENAME
    payload = decode_payload(WINDOWS_PAYLOAD_B64)

    if target.exists():
        try:
            existing = target.read_bytes()
        except OSError:
            existing = None

        if existing == payload:
            info("Shazampy_Win.py is already present in the destination; keeping it.")
        elif force:
            info("Replacing existing Windows Shazampy because --force was requested.")
            if not dry_run:
                target.write_bytes(payload)
        else:
            warn(
                str(target)
                + " already exists and differs from the embedded copy; "
                + "leaving it untouched. Use --force only if you want to replace it."
            )
    else:
        info("Installing Windows Shazampy to " + str(target))
        if not dry_run:
            target.write_bytes(payload)

    if not dry_run:
        bat = dest_dir / "run_shazampy.bat"
        python_exe = sys.executable
        bat.write_text(
            '@echo off\r\n"' + python_exe + '" "' + str(target) + '"\r\n',
            encoding="utf-8",
        )
        ok("Created Windows launcher: " + str(bat))

    return target


def verify_linux():
    missing = []
    for cmd in ("ffmpeg", "songrec", "pactl"):
        if not shutil.which(cmd):
            missing.append(cmd)
    try:
        import tkinter  # noqa
    except Exception:
        missing.append("Python Tkinter module")
    try:
        import requests  # noqa
    except Exception:
        missing.append("Python requests module")
    return missing


