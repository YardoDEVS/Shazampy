def c(text, code):
    if not sys.stdout.isatty():
        return text
    return "\033[" + code + "m" + text + "\033[0m"


def info(msg):
    print(c("[*] ", "36") + msg)


def ok(msg):
    print(c("[+] ", "32") + msg)


def warn(msg):
    print(c("[!] ", "33") + msg)


def fail(msg, exit_code=1):
    print(c("[x] ", "31") + msg, file=sys.stderr)
    raise SystemExit(exit_code)


def run(cmd, check=True, env=None, dry_run=False):
    info("$ " + " ".join(str(part) for part in cmd))
    if dry_run:
        return subprocess.CompletedProcess(cmd, 0, "", "")
    return subprocess.run(cmd, check=check, text=True, env=env)


def decode_payload(payload):
    return zlib.decompress(base64.b64decode(payload))


def read_os_release():
    data = {}
    path = Path("/etc/os-release")
    if not path.exists():
        return data
    for raw in path.read_text(encoding="utf-8", errors="replace").splitlines():
        if "=" not in raw or raw.lstrip().startswith("#"):
            continue
        key, value = raw.split("=", 1)
        data[key] = value.strip().strip('"').strip("'")
    return data


def sudo_prefix():
    if hasattr(os, "geteuid") and os.geteuid() == 0:
        return []
    sudo = shutil.which("sudo")
    if not sudo:
        fail("Administrative privileges are required to install Linux system packages, but sudo was not found.")
    return [sudo]


def pactl_server_ok():
    if not shutil.which("pactl"):
        return False
    try:
        result = subprocess.run(
            ["pactl", "info"],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            timeout=3,
            check=False,
        )
        return result.returncode == 0
    except Exception:
        return False


def start_pipewire_user_services(dry_run):
    if not shutil.which("systemctl"):
        return
    for unit in ("pipewire.socket", "pipewire-pulse.socket", "wireplumber.service"):
        try:
            run(["systemctl", "--user", "enable", "--now", unit], check=False, dry_run=dry_run)
        except Exception:
            pass


def install_arch(dry_run):
    sudo = sudo_prefix()
    packages = [
        "python",
        "python-requests",
        "tk",
        "ffmpeg",
        "songrec",
        "libpulse",
        "playerctl",
        "noto-fonts",
        "noto-fonts-cjk",
        "noto-fonts-emoji",
        "noto-fonts-extra",
    ]
    run(sudo + ["pacman", "-S", "--needed", "--noconfirm"] + packages, dry_run=dry_run)

    if not dry_run and not pactl_server_ok():
        warn("No running PulseAudio-compatible server detected. Installing PipeWire-Pulse.")
        run(
            sudo + ["pacman", "-S", "--needed", "--noconfirm", "pipewire", "pipewire-pulse", "wireplumber"],
            dry_run=dry_run,
        )
        start_pipewire_user_services(dry_run)


def cargo_install_songrec(sudo, dry_run):
    run(
        ["cargo", "install", "songrec", "--no-default-features", "-F", "gui,ffmpeg,pulse,pipewire,mpris"],
        dry_run=dry_run,
    )
    cargo_bin = Path.home() / ".cargo" / "bin" / "songrec"
    if dry_run:
        return
    if not cargo_bin.exists():
        fail("Cargo completed but the SongRec binary was not found.")
    run(sudo + ["ln", "-sf", str(cargo_bin), "/usr/local/bin/songrec"], dry_run=dry_run)


def install_ubuntu_or_debian(os_id, dry_run):
    sudo = sudo_prefix()
    env = os.environ.copy()
    env["DEBIAN_FRONTEND"] = "noninteractive"

    run(sudo + ["apt-get", "update"], env=env, dry_run=dry_run)
    packages = [
        "python3",
        "python3-tk",
        "python3-requests",
        "ffmpeg",
        "pulseaudio-utils",
        "playerctl",
        "fonts-noto",
        "fonts-noto-cjk",
        "fonts-noto-color-emoji",
        "ca-certificates",
        "curl",
    ]
    if os_id == "ubuntu":
        packages.append("software-properties-common")
    run(sudo + ["apt-get", "install", "-y"] + packages, env=env, dry_run=dry_run)

    if os_id == "ubuntu":
        if not shutil.which("songrec") or dry_run:
            info("Installing SongRec from its Ubuntu PPA.")
            run(sudo + ["add-apt-repository", "ppa:marin-m/songrec", "-y"], env=env, dry_run=dry_run)
            run(sudo + ["apt-get", "update"], env=env, dry_run=dry_run)
            run(sudo + ["apt-get", "install", "-y", "songrec"], env=env, dry_run=dry_run)
    elif not shutil.which("songrec") or dry_run:
        info("Building SongRec with Cargo on Debian.")
        build_packages = [
            "cargo", "rustc", "build-essential", "pkg-config",
            "libasound2-dev", "libpulse-dev", "libpipewire-0.3-dev",
            "libclang-dev", "libgtk-4-dev", "libsoup-3.0-dev",
            "libadwaita-1-dev", "libdbus-1-dev", "libssl-dev",
            "gettext", "blueprint-compiler", "sed", "grep",
        ]
        run(sudo + ["apt-get", "install", "-y"] + build_packages, env=env, dry_run=dry_run)
        cargo_install_songrec(sudo, dry_run)

    if not dry_run and not pactl_server_ok():
        warn("No running PulseAudio-compatible server detected. Installing PipeWire-Pulse.")
        run(
            sudo + ["apt-get", "install", "-y", "pipewire", "pipewire-pulse", "wireplumber"],
            env=env,
            dry_run=dry_run,
        )
        start_pipewire_user_services(dry_run)


