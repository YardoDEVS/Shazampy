def main():
    parser = argparse.ArgumentParser(
        description="Install Shazampy on Linux or Windows x64."
    )
    parser.add_argument(
        "--dest",
        default=str(Path.cwd()),
        help="Installation directory. Default: current working directory.",
    )
    parser.add_argument("--yes", action="store_true", help="Do not ask for confirmation.")
    parser.add_argument("--force", action="store_true", help="Overwrite an existing Shazampy script.")
    parser.add_argument(
        "--skip-packages",
        action="store_true",
        help="Only install the Shazampy script; skip dependency installation.",
    )
    parser.add_argument(
        "--skip-fonts",
        action="store_true",
        help="Windows only: do not download the private Noto font collection.",
    )
    parser.add_argument("--dry-run", action="store_true", help="Show actions without changing the system.")
    args = parser.parse_args()

    dest_dir = Path(args.dest).expanduser().resolve()
    if not args.dry_run:
        dest_dir.mkdir(parents=True, exist_ok=True)

    system = platform.system()
    print()
    print(c("Shazampy installer", "1;36"))
    print("Copyright © 2026 Gerardo García Alfaro")
    print("License: CC BY-NC 4.0")
    print("Detected platform: " + system)
    print("Destination: " + str(dest_dir))
    print()

    if system not in ("Linux", "Windows"):
        fail("This installer currently supports Linux and Windows x64.")

    if not args.yes and not args.dry_run:
        answer = input("Continue? [y/N] ").strip().lower()
        if answer not in ("y", "yes"):
            fail("Installation cancelled.", 2)

    if system == "Linux":
        if not args.skip_packages:
            family = install_linux_dependencies(args.dry_run)
            ok("Dependency step completed for: " + family)
        target = write_linux_app(dest_dir, args.force, args.dry_run)
        if not args.dry_run:
            missing = verify_linux()
            if missing:
                warn("Missing required components: " + ", ".join(missing))
                raise SystemExit(3)
            ok("Linux Shazampy installed.")
            print("Run: " + str(target))

    else:
        is_win7 = check_windows_python()
        if is_win7:
            warn(
                "Windows 7 compatibility mode uses Python 3.8 and pinned legacy "
                "dependencies. Windows 7 and Python 3.8 are end-of-life."
            )
        if not args.skip_packages:
            pip_install_windows(args.dry_run)

        target = write_windows_app(dest_dir, args.force, args.dry_run)

        if not args.skip_fonts:
            install_windows_fonts(dest_dir, args.dry_run)

        if not args.dry_run:
            missing = verify_windows()
            if missing:
                warn("Missing required Python components: " + ", ".join(missing))
                raise SystemExit(3)
            ok("Windows Shazampy installed.")
            print("Run: " + str(dest_dir / "run_shazampy.bat"))
            print("Or:  " + str(target))

    if args.dry_run:
        ok("Dry run completed successfully.")


if __name__ == "__main__":
    main()
