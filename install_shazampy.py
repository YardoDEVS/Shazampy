def install_linux_dependencies(dry_run):
    osr = read_os_release()
    os_id = osr.get("ID", "").lower()
    like = osr.get("ID_LIKE", "").lower().split()

    if os_id in ("arch", "manjaro", "endeavouros") or "arch" in like:
        install_arch(dry_run)
        return "Arch Linux family"
    if os_id == "ubuntu":
        install_ubuntu_or_debian("ubuntu", dry_run)
        return "Ubuntu"
    if os_id == "debian" or "debian" in like:
        install_ubuntu_or_debian("debian", dry_run)
        return "Debian family"
    if os_id == "fedora" or "fedora" in like or "rhel" in like:
        install_fedora(dry_run)
        return "Fedora family"

    fail(
        "Automatic Linux package installation currently supports Arch-family, "
        "Ubuntu/Debian-family and Fedora-family systems. Use --skip-packages "
        "after installing Python/Tkinter, requests, ffmpeg, SongRec, pactl and "
        "a PulseAudio-compatible audio server manually."
    )


def windows_version_info():
    release = platform.release()
    version = platform.version()
    return release, version


def check_windows_python():
    if platform.architecture()[0] != "64bit":
        fail("Shazampy_Win.py currently targets Windows x64 only.")

    major, minor = sys.version_info[:2]
    release, version = windows_version_info()

    # Windows 7 cannot run CPython 3.9+ officially. Python 3.8.10 is the last
    # CPython release with an official Windows 7 installer.
    is_win7 = release == "7" or version.startswith("6.1")

    if is_win7:
        if (major, minor) != (3, 8):
            fail(
                "Windows 7 x64 requires Python 3.8.x for this compatibility "
                "profile. Install Python 3.8.10 x64, then run this installer again."
            )
    else:
        if (major, minor) < (3, 8) or (major, minor) > (3, 12):
            fail(
                "Windows 10/11 x64: use Python 3.8 through 3.12 for this release."
            )

    return is_win7


